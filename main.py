def identify_insect():
    print("Ответьте на вопросы (Да/Нет):")

    # Список вопросов и их влияния на разные виды
    questions = [
        "У объекта есть крылья?",
        "Крылья покрыты чешуйками?",
        "Питается нектаром?",
        "Проходит стадию гусеницы?",
        "Активен днем?"
    ]

    # Профили насекомых: {название: [ожидаемые_ответы_с_весами]}
    insects = {
        "Бабочка": [("да", 1), ("да", 0.8), ("да", 0.8), ("да", 1), ("да", 0.4)],
        "Пчела": [("да", 1), ("нет", 0.9), ("да", 0.9), ("нет", 1), ("да", 0.6)],
        "Стрекоза": [("да", 1), ("нет", 0.7), ("нет", 0.8), ("нет", 1), ("да", 0.9)],
        "Мотылек": [("да", 1), ("да", 0.8), ("да", 0.6), ("да", 1), ("нет", 0.8)],
        "Кузнечик": [("да", 0.9), ("нет", 0.7), ("нет", 0.6), ("нет", 0.8), ("да", 0.9)],
        "Муравей": [("нет", 1), ("нет", 0.9), ("нет", 0.7), ("нет", 1), ("да", 0.5)]
    }

    # Сбор ответов
    answers = []
    for q in questions:
        ans = input(q + " ").strip().lower()
        answers.append(ans)

    # Расчет баллов для каждого насекомого
    scores = {}
    for insect, params in insects.items():
        score = 0
        for i in range(len(questions)):
            expected_answer, weight = params[i]
            # Сравниваем ответ с ожидаемым
            if answers[i] == expected_answer:
                score += weight
        scores[insect] = score

    # Определение результата
    max_score = max(scores.values())
    candidates = [k for k, v in scores.items() if v == max_score]

    if max_score == 0:
        print("Не удалось определить насекомое.")
    elif len(candidates) == 1:
        print(f"Это, скорее всего, {candidates[0]} (совпадение: {max_score:.1f} баллов)!")
    else:
        print(f"Это может быть: {', '.join(candidates)} (совпадение: {max_score:.1f} баллов).")


identify_insect()